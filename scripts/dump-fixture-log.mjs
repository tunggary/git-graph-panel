// Prints tests/fixtures/fixture-log.ts for a repository made by make-fixture-repo.sh:
//
//   node scripts/dump-fixture-log.mjs <repo> > tests/fixtures/fixture-log.ts
//
// The tests run in an environment without a shell, so they read git's output from this module.
import { execFileSync } from 'node:child_process'

const repo = process.argv[2]
if (!repo) {
  console.error('usage: node scripts/dump-fixture-log.mjs <repo>')
  process.exit(1)
}

// Keep in sync with LOG_FORMAT in hooks/lib/parse.ts.
const FORMAT = ['%H', '%P', '%an', '%at', '%D', '%s'].join('%x1f')
const git = args => execFileSync('git', ['-C', repo, ...args], { encoding: 'utf8' })

const log = git(['log', '--all', '--date-order', '-z', '--decorate=full', `--format=${FORMAT}`])
const status = git(['status', '--porcelain=v1', '-z'])
const head = git(['rev-parse', 'HEAD']).trim()

console.log('// Generated by scripts/dump-fixture-log.mjs from the repository scripts/make-fixture-repo.sh builds.')
console.log(`export const FIXTURE_HEAD = ${JSON.stringify(head)}`)
console.log(`export const FIXTURE_LOG = ${JSON.stringify(log)}`)
console.log(`export const FIXTURE_STATUS = ${JSON.stringify(status)}`)
